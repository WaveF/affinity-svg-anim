// Exercise real native forms, reorder actions, Clear, apply and undo on our own doc.
const { DocumentPreset } = require('/document');
const { AddChildNodesCommandBuilder } = require('/commands');
const { ShapeNodeDefinition, NodeChildType } = require('/nodes');
const doc = Document.createFromPreset(DocumentPreset.all.filter(p => p.name.includes('A4'))[0], true);
let fails = 0;
const check = (ok, message) => { console.log((ok ? 'ok   ' : 'FAIL ') + message); if (!ok) fails++; };
try {
    const b = AddChildNodesCommandBuilder.create(); b.addNode(ShapeNodeDefinition.createDefault());
    doc.executeCommand(b.createCommand(true, NodeChildType.Main));
    const node = doc.selection.at(0).node;
    const initial = [newTrack('move'), newTrack('fade'), newTrack('skew')];
    doc.executeCommand(buildApplyCommand(doc, loadSelectionState([node]), initial, '__anim').command, false);
    const original = readNodeData(node).raw, originalName = userName(node);
    const s = setupDialog(doc), c = s.ui.animate.c;
    check(!c.moveLeft.isEnabled && c.moveRight.isEnabled, 'Track 1 disables left only');
    check(s.anim.move(-1) === false && c.track.selectedIndex === 0, 'left boundary does not wrap');
    c.track.selectedIndex = 1; s.onChange(); c.fadeTo.value = 17;
    s.anim.move(-1);
    check(c.track.selectedIndex === 0 && s.anim.slots()[0].type === 'fade' && s.anim.slots()[1].type === 'move', 'Track 2 swaps with Track 1 and selection follows');
    check(c.fadeTo.value === 17 && s.anim.slots()[0].to === 17, 'uncommitted form edit moves with its track');
    check(!c.moveLeft.isEnabled && c.moveRight.isEnabled, 'boundary buttons refresh after move');
    s.anim.move(1); s.anim.move(1);
    check(c.track.selectedIndex === 2 && s.anim.peek().map(t => t.type).join() === 'move,skew,fade', 'right action swaps adjacent tracks in order');
    s.anim.move(1);
    check(c.track.selectedIndex === 3 && s.anim.slots()[2] === null && s.anim.slots()[3].type === 'fade', 'swap with empty slot preserves both slots');
    const preset = parseConfig(configText(s.anim, '__anim'));
    check(preset.tracks[2] === null && preset.tracks[3].to === 17, 'JSON preserves reordered slots and edits');
    check(readNodeData(node).raw === original, 'reorder leaves document unchanged before OK');
    c.track.selectedIndex = 7; s.onChange();
    check(c.moveLeft.isEnabled && !c.moveRight.isEnabled, 'Track 8 disables right only');
    check(s.anim.move(1) === false && c.track.selectedIndex === 7, 'right boundary does not wrap');
    c.track.selectedIndex = 3; s.onChange();
    performOk(doc, s);
    check(readNodeData(node).data.tracks.map(t => t.type).join() === 'move,skew,fade', 'OK writes reordered active tracks');
    doc.undo(); check(readNodeData(node).raw === original, 'one undo restores original track order');
    const clear = setupDialog(doc);
    clear.ui.mode.selectedIndex = MODES.indexOf('export');
    clear.ui.animate.c.exportAfter.value = true;
    clear.config.clear();
    check(clear.anim.slots().length === 8 && clear.anim.slots().every(t => t === null), 'Clear empties all eight slots');
    check(clear.ui.animate.c.track.selectedIndex === 0 && !clear.ui.animate.c.moveLeft.isEnabled, 'Clear resets current track and boundary controls');
    check(currentMode(clear.ui) === 'animate' && !clear.ui.animate.c.exportAfter.value, 'Clear from Export returns to Animate and disables implicit export');
    check(readNodeData(node).raw === original && userName(node) === originalName, 'Clear is cancellable: document and layer name untouched before OK');
    check(/^OK removes/.test(clear.ui.okLine.text), 'footer explains Clear applies on OK');
    const h = doc.history.position; performOk(doc, clear);
    check(!readNodeData(node).data && !userName(node).endsWith('__anim'), 'OK clears animation and its layer suffix');
    check(doc.history.position === h + 1, 'Clear advances undo position by one step, including after an undo');
    doc.undo();
    check(readNodeData(node).raw === original && userName(node) === originalName, 'one undo restores all cleared tracks and layer name');
} finally { doc.close(); }
console.log(fails ? fails + ' FAILED' : 'ALL PASSED');
